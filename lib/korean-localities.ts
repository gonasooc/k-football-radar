const localityAlternation = Array.from(new Set(KOREAN_LOCALITY_STEMS))
  .sort((left, right) => right.length - left.length)
  .join("|");
const districtAlternation = Array.from(new Set(KOREAN_DISTRICT_STEMS))
  .sort((left, right) => right.length - left.length)
  .join("|");

const LOCAL_FOOTBALL_ASSOCIATION_PATTERN = new RegExp(
  `(?<![가-힣])(?:(?:${localityAlternation})(?:특별시|광역시|특별자치시|특별자치도|도|시|군|구)?|(?:${districtAlternation})\\s*구)\\s*축구협회`,
  "u"
);

const LOCAL_LIVESTOCK_COOPERATIVE_PATTERN = new RegExp(
  `(?<![가-힣])(?:(?:${localityAlternation})(?:특별시|광역시|특별자치시|특별자치도|도|시|군|구)?|(?:${districtAlternation})\\s*구)\\s*축협`,
  "u"
);

export function hasLocalFootballAssociationContext(text: string): boolean {
  return LOCAL_FOOTBALL_ASSOCIATION_PATTERN.test(text);
}

export function hasNamedLocalLivestockCooperativeContext(text: string): boolean {
  return LOCAL_LIVESTOCK_COOPERATIVE_PATTERN.test(text);
}
